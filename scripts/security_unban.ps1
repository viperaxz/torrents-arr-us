#Requires -RunAsAdministrator
<#
.SYNOPSIS
    Inspect and clear IP bans. The recovery tool for "I locked myself out".

.DESCRIPTION
    Three independent things on this box can block an inbound IP:

      1. CrowdSec decisions  -> enforced by cs-windows-firewall-bouncer
                                as firewall rules named crowdsec-blocklist*
      2. Abuse blocklists    -> Seedbox-Abuse-Blocklist* firewall rules
                                (Spamhaus DROP + Firehol level-1)
      3. Legacy IPBan rules  -> IPBan_* firewall rules, only on installs that
                                predate the CrowdSec migration

    This script reports all three and can clear them. Run it locally (console,
    RDP from the LAN, or over Tailscale) -- those paths are whitelisted and
    stay reachable even when the public path is blocked.

.PARAMETER Ip
    Unban a single address. Removes its CrowdSec decision and drops it out of
    any abuse-blocklist rule that covers it.

.PARAMETER All
    Clear every CrowdSec decision. Does not touch the abuse blocklists.

.PARAMETER Whitelist
    Permanently whitelist the address: adds it to Security.ExtraWhitelistIps in
    config.json. The CrowdSec whitelist parser itself is generated by
    12_security.ps1 from that list, so re-run that script (as printed at the
    end) to apply it. Use for an IP that keeps getting banned, e.g. a static
    office or VPN exit address.

.EXAMPLE
    .\security_unban.ps1
    Show everything currently blocked.

.EXAMPLE
    .\security_unban.ps1 -Ip 203.0.113.44
    Unban one address.

.EXAMPLE
    .\security_unban.ps1 -Ip 203.0.113.44 -Whitelist
    Unban it and make sure it never gets banned again.

.EXAMPLE
    .\security_unban.ps1 -All
    Clear every active CrowdSec ban.
#>
param(
    [string]$Ip,
    [switch]$All,
    [switch]$Whitelist
)

# "Continue", not "Stop": cscli writes normal progress to stderr, and under PS 5.1 a
# terminating EAP turns that into a NativeCommandError. This is a recovery tool -- it
# must keep working when things are already broken, so errors are handled explicitly.
$ErrorActionPreference = "Continue"

$CsCli      = "C:\Program Files\CrowdSec\cscli.exe"
$ConfigPath = Join-Path (Split-Path $PSScriptRoot -Parent) "config.json"
$centralDecisions = @()   # filled by the report below, reused by the -Ip action

function Write-Section($text) {
    Write-Host ""
    Write-Host "== $text " -ForegroundColor Cyan -NoNewline
    Write-Host ("=" * [Math]::Max(0, 66 - $text.Length)) -ForegroundColor Cyan
}

function Test-AddressInRange {
    # True when $Address falls inside $Range (a bare IP or a CIDR).  String
    # matching is not enough here: firewall RemoteAddress values are mostly
    # CIDRs, so "-eq <the unban address>" never matches the rule that actually
    # covers it, while "-like '<first three octets>.*'" also matches unrelated
    # neighbours in the same /24 (and unblocks them).
    param([string]$Address, [string]$Range)
    if (-not $Address -or -not $Range) { return $false }
    $addr = $null
    if (-not [System.Net.IPAddress]::TryParse($Address, [ref]$addr)) { return $false }
    $parts = $Range -split '/', 2
    $net   = $null
    if (-not [System.Net.IPAddress]::TryParse($parts[0], [ref]$net)) { return $false }
    if ($net.AddressFamily -ne $addr.AddressFamily) { return $false }
    $maxLen = if ($addr.AddressFamily -eq [System.Net.Sockets.AddressFamily]::InterNetworkV6) { 128 } else { 32 }
    $len    = $maxLen
    if ($parts.Count -gt 1 -and -not [int]::TryParse($parts[1], [ref]$len)) { return $false }
    if ($len -lt 0 -or $len -gt $maxLen) { return $false }
    $a = $net.GetAddressBytes()
    $b = $addr.GetAddressBytes()
    $full = [int][Math]::Floor($len / 8)
    for ($i = 0; $i -lt $full; $i++) { if ($a[$i] -ne $b[$i]) { return $false } }
    $rem = $len % 8
    if ($rem -gt 0) {
        $mask = [byte](256 - [math]::Pow(2, 8 - $rem))
        if (($a[$full] -band $mask) -ne ($b[$full] -band $mask)) { return $false }
    }
    return $true
}

# -- Report --------------------------------------------------------------------
Write-Section "CrowdSec decisions"
if (-not (Test-Path $CsCli)) {
    Write-Host "  cscli.exe not found at $CsCli -- CrowdSec is not installed." -ForegroundColor Yellow
} else {
    $csSvc  = Get-Service 'crowdsec' -ErrorAction SilentlyContinue
    $bncSvc = Get-Service 'cs-windows-firewall-bouncer' -ErrorAction SilentlyContinue
    Write-Host ("  engine  : {0}" -f $(if ($csSvc)  { $csSvc.Status }  else { 'not installed' })) -ForegroundColor Gray
    Write-Host ("  bouncer : {0}" -f $(if ($bncSvc) { $bncSvc.Status } else { 'not installed' })) -ForegroundColor Gray

    try {
        # --all is required: Community Blocklist decisions (origin CAPI) are
        # enforced by the bouncer exactly like local ones, but a plain
        # `decisions list` hides them.  Reporting "No active decisions" while a
        # dozen crowdsec-blocklist rules are loaded is the worst possible answer
        # for a lockout-recovery tool.  The central set is thousands of IPs, so it
        # is counted rather than listed.
        $raw     = (& $CsCli decisions list --all -o json 2>$null | Out-String).Trim()
        $decCode = $LASTEXITCODE
        if ($decCode -ne 0) {
            # Never report "no active decisions" when the query itself failed --
            # in a lockout-recovery tool that reads as "you are not banned".
            Write-Host "  Could not query decisions (cscli exited $decCode) -- engine or LAPI may be down." -ForegroundColor Yellow
        } elseif ($raw -and $raw -ne 'null' -and $raw -ne '[]') {
            $rows    = [System.Collections.Generic.List[object]]::new()
            $central = [System.Collections.Generic.List[object]]::new()
            foreach ($alert in @($raw | ConvertFrom-Json)) {
                foreach ($d in @($alert.decisions)) {
                    if (-not $d) { continue }
                    $row = [pscustomobject]@{
                        IP       = $d.value
                        Reason   = $d.scenario
                        Duration = $d.duration
                        Origin   = $d.origin
                    }
                    if ("$($d.origin)" -in @('CAPI', 'console')) { $central.Add($row) } else { $rows.Add($row) }
                }
            }
            $centralDecisions = @($central)
            if ($rows.Count -gt 0) { $rows | Format-Table -AutoSize | Out-String | Write-Host }
            else                   { Write-Host "  No locally-sourced decisions." -ForegroundColor Green }
            if ($central.Count -gt 0) {
                Write-Host "  $($central.Count) central decision(s) from the Community Blocklist (origin CAPI)" -ForegroundColor Yellow
                Write-Host "  are also being enforced; those are managed by the CrowdSec Console, not here." -ForegroundColor DarkGray
            }
        } else {
            Write-Host "  No active decisions." -ForegroundColor Green
        }
    } catch {
        Write-Host "  Could not query decisions: $_" -ForegroundColor Yellow
    }
}

Write-Section "Firewall block rules"
foreach ($pattern in @("crowdsec-blocklist*", "Seedbox-Abuse-Blocklist*", "IPBan_*")) {
    $rules = @(Get-NetFirewallRule -DisplayName $pattern -ErrorAction SilentlyContinue)
    Write-Host ("  {0,-28} {1} rule(s)" -f $pattern, $rules.Count) -ForegroundColor Gray
}

# -- Actions -------------------------------------------------------------------
if ($All) {
    Write-Section "Clearing all CrowdSec decisions"
    if (Test-Path $CsCli) {
        & $CsCli decisions delete --all
        if ($LASTEXITCODE -eq 0) {
            Write-Host "  All CrowdSec decisions cleared." -ForegroundColor Green
            Write-Host "  The bouncer syncs within ~10s; firewall rules clear themselves." -ForegroundColor DarkGray
            if ($centralDecisions.Count -gt 0) {
                Write-Host "  $($centralDecisions.Count) central decision(s) (Community Blocklist) are NOT affected --" -ForegroundColor Yellow
                Write-Host "  those are managed by the CrowdSec Console." -ForegroundColor Yellow
            }
        } else {
            Write-Host "  cscli exited $LASTEXITCODE -- decisions may not have cleared." -ForegroundColor Yellow
        }
    } else {
        Write-Host "  CrowdSec not installed -- nothing to clear." -ForegroundColor Yellow
    }
}

# A typo must not reach cscli, the firewall rules, or config.json.
if ($Ip) {
    $parsedIp = $null
    if (-not [System.Net.IPAddress]::TryParse($Ip, [ref]$parsedIp)) {
        Write-Host ""
        Write-Host "  '$Ip' is not a valid IP address -- nothing changed." -ForegroundColor Yellow
        $Ip = $null
    }
}

if ($Ip) {
    Write-Section "Unbanning $Ip"

    if (Test-Path $CsCli) {
        & $CsCli decisions delete --ip $Ip
        if ($LASTEXITCODE -eq 0) {
            Write-Host "  CrowdSec decision(s) removed for $Ip." -ForegroundColor Green
        } elseif (@($centralDecisions | Where-Object { $_.IP -eq $Ip }).Count -gt 0) {
            Write-Host "  $Ip is banned by the Community Blocklist (origin CAPI)." -ForegroundColor Yellow
            Write-Host "  Those decisions are managed centrally and cannot be deleted on this box --" -ForegroundColor DarkGray
            Write-Host "  override it in the CrowdSec Console, or wait for it to expire." -ForegroundColor DarkGray
        } else {
            Write-Host "  cscli exited $LASTEXITCODE for $Ip (may simply not have been banned)." -ForegroundColor DarkGray
        }
    }

    # The abuse blocklists are static reputation lists, not CrowdSec decisions --
    # they need their own removal, and the rule must be rebuilt without the entry.
    $hit = $false
    foreach ($rule in @(Get-NetFirewallRule -DisplayName "Seedbox-Abuse-Blocklist*" -ErrorAction SilentlyContinue)) {
        $filter  = $rule | Get-NetFirewallAddressFilter
        $remotes = @($filter.RemoteAddress)
        $match   = @($remotes | Where-Object { Test-AddressInRange -Address $Ip -Range $_ })
        if ($match.Count -gt 0) {
            $hit = $true
            Write-Host "  Found in $($rule.DisplayName): $($match -join ', ')" -ForegroundColor Yellow
            $kept = @($remotes | Where-Object { $_ -notin $match })
            if ($kept.Count -gt 0) {
                $rule | Set-NetFirewallRule -RemoteAddress $kept
                Write-Host "  Removed from $($rule.DisplayName) ($($kept.Count) entries remain)." -ForegroundColor Green
            } else {
                $rule | Remove-NetFirewallRule
                Write-Host "  Rule $($rule.DisplayName) was only this entry -- removed." -ForegroundColor Green
            }
        }
    }
    if (-not $hit) {
        Write-Host "  Not present in any abuse blocklist rule." -ForegroundColor DarkGray
    }

    if ($Whitelist) {
        Write-Section "Whitelisting $Ip permanently"
        if (-not (Test-Path $ConfigPath)) {
            Write-Host "  config.json not found at $ConfigPath -- cannot persist." -ForegroundColor Yellow
        } else {
            # config.json is the user's live configuration. It is never
            # re-serialised: ConvertTo-Json would reformat the whole file, and an
            # unparseable config.json would make it emit the literal "null",
            # destroying everything (secrets included). So: parse only to
            # validate, then do a surgical text insert, then verify the result
            # before trusting it -- with a backup to fall back on.
            $rawBytes = [System.IO.File]::ReadAllBytes($ConfigPath)
            $hasBom   = $rawBytes.Length -ge 3 -and $rawBytes[0] -eq 0xEF -and
                        $rawBytes[1] -eq 0xBB -and $rawBytes[2] -eq 0xBF
            $rawJson  = [System.IO.File]::ReadAllText($ConfigPath)   # strips a BOM when decoding
            $parsed   = $null
            try { $parsed = $rawJson | ConvertFrom-Json -ErrorAction Stop } catch { $parsed = $null }

            if (-not $parsed -or -not $parsed.PSObject.Properties['Security']) {
                Write-Host "  config.json could not be parsed, or has no Security block." -ForegroundColor Yellow
                Write-Host "  Nothing was written. Add the entry by hand:" -ForegroundColor Yellow
                Write-Host "    `"Security`": { `"ExtraWhitelistIps`": [`"$Ip`"] }" -ForegroundColor Gray
            } else {
                $existing = @($parsed.Security.ExtraWhitelistIps)
                if ($existing -contains $Ip) {
                    Write-Host "  $Ip is already in Security.ExtraWhitelistIps." -ForegroundColor DarkGray
                } else {
                    $newJson = $null

                    # Append to the existing array literal, byte-for-byte otherwise.
                    $m = [regex]::Match($rawJson, '("ExtraWhitelistIps"\s*:\s*)\[(?<items>[^\]]*)\]')
                    if ($m.Success) {
                        $items    = $m.Groups['items'].Value.Trim()
                        $entry    = '"' + $Ip + '"'
                        $newItems = if ($items) { $items + ', ' + $entry } else { $entry }
                        $start    = $m.Groups['items'].Index
                        $newJson  = $rawJson.Substring(0, $start) + $newItems +
                                    $rawJson.Substring($start + $m.Groups['items'].Length)
                    } elseif ($rawJson -match '"ExtraWhitelistIps"\s*:') {
                        # The key exists, but not as a JSON array (e.g. a bare string).
                        # Adding a second "ExtraWhitelistIps" key parses fine -- the
                        # last one wins -- and the verification below would pass, so
                        # the operator's original value would be lost silently. Refuse.
                        Write-Host "  Security.ExtraWhitelistIps exists but is not a JSON array -- nothing written." -ForegroundColor Yellow
                        Write-Host "  Add `"$Ip`" to it by hand; the value must be an array: [`"$Ip`"]" -ForegroundColor Gray
                    } else {
                        # Security block present but no ExtraWhitelistIps key.
                        $m = [regex]::Match($rawJson, '("Security"\s*:\s*\{)')
                        if ($m.Success) {
                            $nl   = if ($rawJson -match "`r`n") { "`r`n" } else { "`n" }
                            $ins  = $nl + '    "ExtraWhitelistIps": ["' + $Ip + '"],'
                            $pos  = $m.Groups[1].Index + $m.Groups[1].Length
                            $newJson = $rawJson.Substring(0, $pos) + $ins + $rawJson.Substring($pos)
                        } else {
                            Write-Host "  Could not locate the Security block in config.json -- nothing written." -ForegroundColor Yellow
                        }
                    }

                    if ($newJson) {
                        $backup = "$ConfigPath.bak"
                        Copy-Item -LiteralPath $ConfigPath -Destination $backup -Force
                        # Re-emit the original BOM (if any) so the edit is the only
                        # byte-level change in the file.
                        $outText = if ($hasBom) { [string][char]0xFEFF + $newJson } else { $newJson }
                        [System.IO.File]::WriteAllText($ConfigPath, $outText, (New-Object System.Text.UTF8Encoding($false)))

                        $verify = $null
                        try { $verify = [System.IO.File]::ReadAllText($ConfigPath) | ConvertFrom-Json -ErrorAction Stop } catch { $verify = $null }
                        if ($verify -and (@($verify.Security.ExtraWhitelistIps) -contains $Ip)) {
                            Write-Host "  Added $Ip to Security.ExtraWhitelistIps in config.json." -ForegroundColor Green
                            Write-Host "  (unchanged backup: $backup)" -ForegroundColor DarkGray
                        } else {
                            Copy-Item -LiteralPath $backup -Destination $ConfigPath -Force
                            Write-Host "  Verification failed -- config.json restored from $backup." -ForegroundColor Red
                        }
                    }
                }
            }

            Write-Host "  Re-run the security installer to apply it to CrowdSec:" -ForegroundColor DarkGray
            Write-Host "    Remove-Item '<InstallDir>\.locks\.security.lock'" -ForegroundColor DarkGray
            Write-Host "    .\scripts\12_security.ps1 -Config (Get-Content .\config.json | ConvertFrom-Json)" -ForegroundColor DarkGray
        }
    }
}

if (-not $Ip -and -not $All) {
    Write-Section "Usage"
    Write-Host "  .\security_unban.ps1 -Ip 1.2.3.4              unban one address"      -ForegroundColor Gray
    Write-Host "  .\security_unban.ps1 -Ip 1.2.3.4 -Whitelist   unban + never ban again" -ForegroundColor Gray
    Write-Host "  .\security_unban.ps1 -All                     clear every ban"         -ForegroundColor Gray
    Write-Host ""
    Write-Host "  Always reachable even when banned: LAN (192.168.x), Tailscale (100.64/10)," -ForegroundColor DarkGray
    Write-Host "  and the local console -- all whitelisted at CrowdSec's enrich stage."       -ForegroundColor DarkGray
}
Write-Host ""
